/* ---------- Comportamientos comunes ---------- */
document.addEventListener('DOMContentLoaded', () => {
  const shell = document.querySelector('.shell');
  // Menú lateral en celular: botón ☰ y fondo oscuro para cerrar
  document.querySelectorAll('.burger, .scrim').forEach((b) =>
    b.addEventListener('click', () => shell && shell.classList.toggle('menu-abierto')));
  // Pestañas: marca la pestaña elegida (filtra la tabla si las filas tienen data-estado)
  document.querySelectorAll('.tabs').forEach((tabs) => {
    tabs.addEventListener('click', (e) => {
      const b = e.target.closest('button'); if (!b) return;
      tabs.querySelectorAll('button').forEach((x) => x.setAttribute('aria-selected', String(x === b)));
      const f = b.dataset.filtro;
      const tabla = document.querySelector(tabs.dataset.tabla || '.tbl');
      if (tabla) tabla.querySelectorAll('tbody tr').forEach((tr) => { tr.hidden = !!f && tr.dataset.estado !== f; });
    });
  });
});
